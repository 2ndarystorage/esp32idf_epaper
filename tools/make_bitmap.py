#!/usr/bin/env python3
"""
日本語テキスト -> e-Paper用 1bitビットマップ (Cヘッダ) 変換ツール

このモジュールのフォントはASCIIのみなので、日本語はPCで画像化して
epaper_fb_draw_bitmap() で描く。使い方:

  pip install Pillow
  python3 tools/make_bitmap.py "こんにちは" --size 32 --out main/text_bitmap.h

フォントは --font で .ttf/.otf を指定する (省略時は代表的なパスを自動探索)。
生成されたヘッダを main にコピーして:

  #include "text_bitmap.h"
  epaper_fb_draw_bitmap(10, 80, TEXT_BITMAP_WIDTH, TEXT_BITMAP_HEIGHT,
                        TEXT_BITMAP_DATA, EPAPER_BLACK);

プレビュー用に <out>.png も同時に出力する。
"""
import argparse
import os
import sys

FONT_CANDIDATES = [
    "/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc",
    "/usr/share/fonts/truetype/noto/NotoSansCJK-Regular.ttc",
    "/System/Library/Fonts/ヒラギノ角ゴシック W3.ttc",  # macOS
    "/System/Library/Fonts/Hiragino Sans GB.ttc",
    "C:\\Windows\\Fonts\\msgothic.ttc",
]


def find_font(explicit):
    if explicit:
        return explicit
    for path in FONT_CANDIDATES:
        if os.path.exists(path):
            return path
    sys.exit("日本語フォントが見つかりません。--font で .ttf/.otf を指定してください")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("text", help="表示したい文字列")
    ap.add_argument("--size", type=int, default=32, help="フォントサイズpx (既定32)")
    ap.add_argument("--font", default=None, help="フォントファイルのパス")
    ap.add_argument("--out", default="text_bitmap.h", help="出力ヘッダのパス")
    args = ap.parse_args()

    try:
        from PIL import Image, ImageDraw, ImageFont
    except ImportError:
        sys.exit("Pillow が必要です: pip install Pillow")

    font = ImageFont.truetype(find_font(args.font), args.size)
    dummy = Image.new("1", (8, 8), 1)
    d = ImageDraw.Draw(dummy)
    bbox = d.textbbox((0, 0), args.text, font=font)
    w = bbox[2] - bbox[0]
    h = bbox[3] - bbox[1]
    # 幅は8の倍数に切り上げ (draw_bitmap の行バイト計算と一致させる)
    w_pad = (w + 7) // 8 * 8

    img = Image.new("1", (w_pad, h), 1)  # 1=白
    d = ImageDraw.Draw(img)
    d.text((-bbox[0], -bbox[1]), args.text, font=font, fill=0)  # 0=黒

    row_bytes = w_pad // 8
    data = []
    px = img.load()
    for y in range(h):
        for xb in range(row_bytes):
            byte = 0
            for bit in range(8):
                x = xb * 8 + bit
                if x < w_pad and px[x, y] == 0:  # 黒画素を bit=1 で表す
                    byte |= 0x80 >> bit
            data.append(byte)

    lines = []
    lines.append("/* generated by tools/make_bitmap.py : %r size=%d */" % (args.text, args.size))
    lines.append("#pragma once")
    lines.append("#include <stdint.h>")
    lines.append("#define TEXT_BITMAP_WIDTH  %d" % w_pad)
    lines.append("#define TEXT_BITMAP_HEIGHT %d" % h)
    lines.append("static const uint8_t TEXT_BITMAP_DATA[] = {")
    for i in range(0, len(data), row_bytes):
        chunk = ", ".join("0x%02X" % b for b in data[i:i + row_bytes])
        lines.append("    " + chunk + ",")
    lines.append("};")
    with open(args.out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")

    png_path = args.out + ".png"
    img.save(png_path)
    print("wrote %s (%dx%d) and preview %s" % (args.out, w_pad, h, png_path))


if __name__ == "__main__":
    main()
